// Returns the glyph for `c`, or nullptr if the font does not cover it.
inline const Glyph* findGlyph(char c) {
    for (const Glyph& g : Glyphs) {
        if (g.c == c) return &g;
    }
    return nullptr;
}

inline int textWidth(const char* text, int scale) {
    int n = 0;
    while (text[n] != '\0') ++n;
    return n == 0 ? 0 : (n * GlyphAdvance - 1) * scale;
}

// Calls fillRect(x, y, w, h) once per lit pixel of `text`. Renderer-agnostic.
template <class FillRect>
void forEachTextPixel(const char* text, int x, int y, int scale, FillRect&& fillRect) {
    for (const char* p = text; *p != '\0'; ++p, x += GlyphAdvance * scale) {
        const Glyph* g = findGlyph(*p);
        if (!g) continue;
        for (int row = 0; row < GlyphH; ++row) {
            for (int col = 0; col < GlyphW; ++col) {
                if (g->rows[row] & (1U << (GlyphW - 1 - col))) {
                    fillRect(x + col * scale, y + row * scale, scale, scale);
                }
            }
        }
    }
}

